"""MCP-Zero's MCP-tools (xfey/MCP-Zero): 308 MCP servers and 2,797 tools from the official MCP
servers list, the corpus of the paper's tool-retrieval experiment.

MCP-tools ships no queries. The paper's experiment hands an LLM one target tool as
``I need to {tool description} with a MCP server of {server description}.`` under MCP-Zero's
system prompt, reads back a ``<tool_assistant> server: ... tool: ... </tool_assistant>`` request,
matches it hierarchically (servers, then their tools, text-embedding-3-large) and scores a hit
when the top tool is the target: accuracy, i.e. Recall@1 with one gold tool. Here every tool is
the target of one query, generated by a local ``ChatModel`` with the same two prompts, and the
query is the request's two lines, so a flat scorer sees all of it. The local generator and flat
retrieval are the deviations to report (the paper used Claude 3.5 Sonnet and GPT-4.1).

Server names are not unique (14 exist twice or three times: an official and a community
``Slack``...), so a tool's id is its server's README path plus its name, ``community/Slack/<tool>``.
The paper scores a hit by server and tool *name*, so every tool sharing both with the target is
relevant too (1-3 per query). ``Tool.category`` is the server name. Parameters come condensed,
``{"name": "(Optional, type) description"}``, and are expanded back to an MCP ``inputSchema`` so
the formats render them like LiveMCPBench's; the precomputed embeddings are dropped. The file
(333 MB) is only on Google Drive and is downloaded once to ``<out>/raw/``.
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import urllib.request
from collections import defaultdict
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Any

from toolrank.datasets.jsonl import write_queries, write_tools
from toolrank.domain import Query, Tool
from toolrank.ports import ChatModel

COMMIT = "fd666c44c9290a671949b974444c30f4ab161622"  # prompts: main, 2025-07-02
DRIVE_ID = "1RjBGU-AGdHdhUABoeYSztbfQlD0hjUBn"  # README's MCP-tools link
DRIVE_URL = f"https://drive.usercontent.google.com/download?id={DRIVE_ID}&export=download&confirm=t"
RAW_FILE = "mcp_tools_with_embedding.json"
TASK = "mcp-tools"
INSTRUCTION = "Given an agent's request for a tool, retrieve the MCP tool that fulfills it."

# MCP-zero/prompt_guide/system_ours_mcptools.prompt and user_query_with_server.prompt, verbatim
SYSTEM_PROMPT = (
    "You are an AI assistant that helps users by analyzing their requests and identifying appropriate "
    "tools. Your task is to identify both the SERVER (platform/service domain) and the specific TOOL "
    "(operation type + target) that would best address the user's request.\n\n"
    "When a user asks you to perform a task, you should:\n"
    "1. Carefully read and understand the user's request\n"
    "2. Identify the key requirements and intentions in the request\n"
    "3. Determine the information of the server from user's request (SERVER)\n"
    "4. Determine what specific tool from user's request (TOOL)\n"
    "5. Respond using ONLY the following format:\n\n"
    "<tool_assistant>\n"
    "server: [brief description of the server/platform from user's request]\n"
    "tool: [brief description of the specific tool from user's request]\n"
    "</tool_assistant>\n\n"
    "Your response should be concise but descriptive.\n"
    "Remember to ONLY provide the server and tool descriptions within the <tool_assistant> tags. "
    "DO NOT provide any additional explanation or commentary outside the <tool_assistant> tags. "
)
USER_PROMPT = "I need to {tool_description} with a MCP server of {server_description}."

_PARAM = re.compile(r"^\s*\(([^)]*)\)\s*(.*)$", re.DOTALL)
_FLAG = re.compile(
    r"\b(optional|required)\b\s*,?\s*", re.IGNORECASE
)  # "(string, required)", "(Optional, int)"
_REQUEST = re.compile(r"<tool_assistant>\s*server:\s*(.*?)\s*tool:\s*(.*?)\s*</tool_assistant>", re.DOTALL)
_THINK = re.compile(r"<think>.*?</think>", re.DOTALL)


def input_schema(params: Any) -> dict[str, Any] | None:
    """``{"q": "(string) Query", "n": "(Optional, integer) Limit"}`` -> an MCP ``inputSchema``.

    The dataset's LLM extraction is loose about the parenthesis (``string, required``, ``optional
    string``, ``default: 300``): "optional" marks an optional parameter, "required"/"optional" are
    dropped from the type, and whatever else is in there is kept as the type.
    """
    if not isinstance(params, dict) or not params:
        return None
    props: dict[str, Any] = {}
    required: list[str] = []
    for name, spec in params.items():
        text, ptype, optional = "" if spec is None else str(spec), "", False
        if m := _PARAM.match(text):
            optional = bool(re.search(r"\boptional\b", m.group(1), re.IGNORECASE))
            ptype = _FLAG.sub("", m.group(1)).strip(" ,")
            text = m.group(2).strip()
        props[str(name)] = {k: v for k, v in (("type", ptype), ("description", text)) if v}
        if not optional:
            required.append(str(name))
    schema: dict[str, Any] = {"type": "object", "properties": props}
    if required:
        schema["required"] = required
    return schema


def user_prompt(server: dict[str, Any], tool: dict[str, Any]) -> str:
    """The request prompt for one target tool; ``str.replace`` as in MCP-Zero's code, so braces
    in descriptions are safe."""
    return USER_PROMPT.replace("{server_description}", str(server.get("description") or "")).replace(
        "{tool_description}", str(tool.get("description") or "")
    )


def convert(servers: list[dict[str, Any]]) -> tuple[list[Tool], dict[str, str], int]:
    """-> (tools, request prompt per tool id, tools dropped because their server already has a
    tool of that name)."""
    tools: list[Tool] = []
    prompts: dict[str, str] = {}
    duplicates = 0
    for srv in servers:
        server = str(srv.get("name") or "")
        key = re.sub(r"\.md$", "", str(srv.get("readme_file") or "")) or server
        for t in srv.get("tools") or []:
            tid = f"{key}/{t.get('name')}"
            if tid in prompts:
                duplicates += 1
                continue
            doc: dict[str, Any] = {
                "name": str(t.get("name") or ""),
                "description": str(t.get("description") or ""),
            }
            if schema := input_schema(t.get("parameter")):
                doc["inputSchema"] = schema
            tools.append(
                Tool(id=tid, doc=doc, documentation=json.dumps(doc, ensure_ascii=False), category=server)
            )
            prompts[tid] = user_prompt(srv, t)
    return tools, prompts, duplicates


def parse_request(response: str) -> tuple[str, str] | None:
    """The ``(server, tool)`` lines of a ``<tool_assistant>`` block (MCP-Zero's regex), else None."""
    m = _REQUEST.search(_THINK.sub("", response or ""))
    return (m.group(1).strip(), m.group(2).strip()) if m else None


def query_text(response: str) -> tuple[str, bool]:
    """-> (query text, parsed). A response without a request block stays a query with its own
    text, so every scorer is measured on the same queries."""
    if req := parse_request(response):
        return f"server: {req[0]}\ntool: {req[1]}", True
    return _THINK.sub("", response or "").strip(), False


def make_queries(tools: list[Tool], responses: dict[str, str]) -> tuple[list[Query], int]:
    """One query per tool with a response -> (queries, responses without a request block).
    Relevant: every tool with the target's server name and tool name (MCP-Zero's hit test)."""
    same: dict[tuple[str, str], list[str]] = defaultdict(list)
    for t in tools:
        same[(t.category, t.name)].append(t.id)
    queries: list[Query] = []
    unparsed = 0
    for t in tools:
        if t.id not in responses:
            continue
        text, ok = query_text(responses[t.id])
        unparsed += not ok
        qrels = dict.fromkeys(same[(t.category, t.name)], 1)
        queries.append(Query(id=t.id, text=text, qrels=qrels, instruction=INSTRUCTION, task=TASK))
    return queries, unparsed


def generate(
    chat: ChatModel,
    prompts: dict[str, str],
    cache: str | Path,
    *,
    workers: int = 32,
    log: Callable[[str], None] = print,
    system: str = SYSTEM_PROMPT,
) -> dict[str, str]:
    """Ask ``chat`` every prompt under ``system`` (MCP-Zero's system prompt) -> {id: response}.

    Responses are appended to ``cache`` (JSONL) as they arrive and reused when model name and
    prompt match, so an interrupted pull resumes and a parser change needs no new generation.
    Delete the file to regenerate with other sampling settings or another system prompt (the key
    is the user prompt).
    """
    path = Path(cache)
    done: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            r = json.loads(line) if line.strip() else {}
            if r and r.get("model") == chat.name and prompts.get(r["id"]) == r.get("prompt"):
                done[r["id"]] = r["response"]
    todo = [i for i in prompts if i not in done]
    if not todo:
        return done
    log(f"generating {len(todo)} requests with {chat.name} ({len(done)} cached)")
    path.parent.mkdir(parents=True, exist_ok=True)
    pool = ThreadPoolExecutor(max_workers=workers)
    try:
        with path.open("a", encoding="utf-8") as f:
            futures = {pool.submit(chat.complete, system, prompts[i]): i for i in todo}
            for n, fut in enumerate(as_completed(futures), 1):
                i = futures[fut]
                done[i] = fut.result()
                row = {"id": i, "model": chat.name, "prompt": prompts[i], "response": done[i]}
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
                if n % 500 == 0 or n == len(todo):
                    f.flush()
                    log(f"  {n}/{len(todo)}")
    finally:  # on an endpoint error, don't wait for thousands of queued requests to retry
        pool.shutdown(wait=False, cancel_futures=True)
    return done


def _download(url: str, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_name(dest.name + ".part")
    with urllib.request.urlopen(url, timeout=120) as r, part.open("wb") as f:
        shutil.copyfileobj(r, f, 1 << 20)
    with part.open("rb") as f:
        if f.read(64).lstrip()[:1] != b"[":
            raise RuntimeError(
                f"Google Drive returned something other than the JSON file; download {url} by hand to {dest}"
            )
    part.replace(dest)


def pull_mcp_zero(
    out_dir: str | Path, chat: ChatModel, *, workers: int = 32, log: Callable[[str], None] = print
) -> dict[str, int]:
    """Download MCP-tools, generate one request per tool with ``chat`` and write ``tools.jsonl``
    + ``queries.jsonl``; -> counts (servers, tools, queries, duplicates, unparsed)."""
    out = Path(out_dir)
    raw = out / "raw" / RAW_FILE
    if not raw.exists():
        log(f"downloading {RAW_FILE} (333 MB) from Google Drive")
        _download(DRIVE_URL, raw)
    data = raw.read_bytes()
    servers = json.loads(data)
    tools, prompts, duplicates = convert(servers)
    responses = generate(chat, prompts, out / "generations.jsonl", workers=workers, log=log)
    queries, unparsed = make_queries(tools, responses)
    write_tools(out / "tools.jsonl", tools)
    write_queries(out / "queries.jsonl", queries)
    (out / "SOURCE.md").write_text(
        f"MCP-Zero MCP-tools - https://github.com/xfey/MCP-Zero (prompts at {COMMIT})\n"
        f"{RAW_FILE}: Google Drive {DRIVE_ID}, sha256 {hashlib.sha256(data).hexdigest()}\n"
        f"queries: one per tool, generated by {chat.name} (generations.jsonl)\n"
    )
    return {
        "servers": len(servers),
        "tools": len(tools),
        "queries": len(queries),
        "duplicates": duplicates,
        "unparsed": unparsed,
    }
